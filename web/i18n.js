export const DICTS = { en: EN, 'zh-TW': ZH };

let lang = 'en';

export function detectLang(search = globalThis.location?.search || '') {
  const q = new URLSearchParams(search).get('lang');
  if (q && LANGS.includes(q)) return q;
  try {
    const saved = globalThis.localStorage?.getItem(STORE_KEY);
    if (saved && LANGS.includes(saved)) return saved;
  } catch {}
  const nav = (globalThis.navigator?.languages?.[0] || globalThis.navigator?.language || 'en').toLowerCase();
  return nav.startsWith('zh') ? 'zh-TW' : 'en';
}

export function setLang(l, { persist = false } = {}) {
  lang = LANGS.includes(l) ? l : 'en';
  if (persist) {
    try {
      globalThis.localStorage?.setItem(STORE_KEY, lang);
    } catch {}
  }
  if (globalThis.document) globalThis.document.documentElement.lang = lang;
  return lang;
}

export function getLang() {
  return lang;
}

export function t(key, vars = {}) {
  const s = DICTS[lang][key] ?? EN[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : String(vars[k])));
}

export function moveLabel(id) {
  return MOVES[lang][id] || MOVES.en[id] || String(id).replace(/_/g, ' ');
}

// Decision sources come from the protocol in English ("reflex 2", "fallback (low confidence)").
export function sourceLabel(src = '') {
  if (src.startsWith('reflex')) return t('src.reflex', { n: src.split(' ')[1] });
  if (src === 'strategy') return t('src.strategy');
  if (src === 'fallback (low confidence)') return t('src.fallbackLow');
  if (src === 'fallback (no answer)') return t('src.fallbackNone');
  if (src === 'nothing ready') return t('src.nothingReady');
  return src;
}

// Fill every element marked with data-i18n (text), data-i18n-html, data-i18n-ph (placeholder)
// or data-i18n-title (tooltip).
export function applyI18n(root = globalThis.document) {
  if (!root) return;
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-html]').forEach((el) => (el.innerHTML = t(el.dataset.i18nHtml)));
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => (el.title = t(el.dataset.i18nTitle)));
}
